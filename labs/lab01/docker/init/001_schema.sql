CREATE SCHEMA IF NOT EXISTS lab01;

CREATE TABLE IF NOT EXISTS lab01.accounts (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    account_id varchar NOT NULL,
    saldo_atual numeric NOT NULL,
    CONSTRAINT accounts_pk PRIMARY KEY (id),
    CONSTRAINT accounts_unique UNIQUE (account_id),
    CONSTRAINT accounts_balance_precision_ck
        CHECK (
            saldo_atual > '-Infinity'::numeric
            AND saldo_atual < 'Infinity'::numeric
            AND saldo_atual = trunc(saldo_atual, 2)
        )
);

CREATE TABLE IF NOT EXISTS lab01.inbound_events (
    event_id varchar NOT NULL,
    account_id varchar NOT NULL,
    operation varchar NOT NULL,
    amount numeric NOT NULL,
    currency varchar NOT NULL,
    status_evento varchar NOT NULL,
    id integer GENERATED BY DEFAULT AS IDENTITY,
    CONSTRAINT inbound_events_pk PRIMARY KEY (id),
    CONSTRAINT inbound_events_unique UNIQUE (event_id),
    CONSTRAINT inbound_events_operation_ck
        CHECK (operation IN ('CREDIT', 'DEBIT')),
    CONSTRAINT inbound_events_amount_ck
        CHECK (
            amount > 0
            AND amount < 'Infinity'::numeric
            AND amount = trunc(amount, 2)
        ),
    CONSTRAINT inbound_events_currency_ck CHECK (currency = 'BRL'),
    CONSTRAINT inbound_events_status_ck
        CHECK (status_evento IN ('RECEIVED', 'PROCESSED')),
    CONSTRAINT inbound_events_business_key
        UNIQUE (event_id, account_id, operation, amount, currency),
    CONSTRAINT inbound_events_accounts_fk
        FOREIGN KEY (account_id) REFERENCES lab01.accounts (account_id)
);

CREATE TABLE IF NOT EXISTS lab01.transactions (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    account_id varchar NOT NULL,
    event_id varchar NOT NULL,
    valor numeric NOT NULL,
    operacao varchar NOT NULL,
    currency varchar NOT NULL,
    CONSTRAINT transactions_pk PRIMARY KEY (id),
    CONSTRAINT transactions_unique_1 UNIQUE (event_id),
    CONSTRAINT transactions_operation_ck
        CHECK (operacao IN ('CREDIT', 'DEBIT')),
    CONSTRAINT transactions_amount_ck
        CHECK (
            valor > 0
            AND valor < 'Infinity'::numeric
            AND valor = trunc(valor, 2)
        ),
    CONSTRAINT transactions_currency_ck CHECK (currency = 'BRL'),
    CONSTRAINT transactions_accounts_fk
        FOREIGN KEY (account_id) REFERENCES lab01.accounts (account_id),
    CONSTRAINT transactions_inbound_events_fk
        FOREIGN KEY (event_id, account_id, operacao, valor, currency)
        REFERENCES lab01.inbound_events
            (event_id, account_id, operation, amount, currency)
);

