-- Migração única para alinhar o DDL documentado aos repositórios do LAB01.
-- Revise os dados existentes e faça backup antes de aplicar em um banco com dados.
BEGIN;

ALTER TABLE lab01.accounts
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE lab01.inbound_events
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE lab01.transactions
    ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

SELECT setval(
    pg_get_serial_sequence('lab01.accounts', 'id'),
    COALESCE(MAX(id), 1),
    MAX(id) IS NOT NULL
) FROM lab01.accounts;
SELECT setval(
    pg_get_serial_sequence('lab01.inbound_events', 'id'),
    COALESCE(MAX(id), 1),
    MAX(id) IS NOT NULL
) FROM lab01.inbound_events;
SELECT setval(
    pg_get_serial_sequence('lab01.transactions', 'id'),
    COALESCE(MAX(id), 1),
    MAX(id) IS NOT NULL
) FROM lab01.transactions;

ALTER TABLE lab01.transactions
    DROP CONSTRAINT IF EXISTS transactions_accounts_fk,
    DROP CONSTRAINT IF EXISTS transactions_inbound_events_fk;

ALTER TABLE lab01.inbound_events
    ADD CONSTRAINT inbound_events_accounts_fk
    FOREIGN KEY (account_id) REFERENCES lab01.accounts (account_id);

ALTER TABLE lab01.transactions
    ADD CONSTRAINT transactions_accounts_fk
        FOREIGN KEY (account_id) REFERENCES lab01.accounts (account_id),
    ADD CONSTRAINT transactions_inbound_events_fk
        FOREIGN KEY (event_id) REFERENCES lab01.inbound_events (event_id);

COMMIT;
